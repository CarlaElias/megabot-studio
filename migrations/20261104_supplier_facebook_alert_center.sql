-- MegaBot: alertas permanentes del proveedor para revisar publicaciones Facebook Marketplace.
-- Se genera al cambiar supplier_stock, supplier_status o supplier_unit_price.
-- No modifica stock propio ni precio de venta. Seguro al ejecutar varias veces.
CREATE TABLE IF NOT EXISTS public.supplier_alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
 kind VARCHAR(24) NOT NULL CHECK (kind IN ('nuevo','agotado','repuesto','precio_subio','precio_bajo')),
 old_supplier_stock INTEGER NULL,
 new_supplier_stock INTEGER NULL,
 old_supplier_unit_price NUMERIC(12,2) NULL,
 new_supplier_unit_price NUMERIC(12,2) NULL,
 source_label VARCHAR(160) NOT NULL DEFAULT 'Cambio detectado en catálogo importadora',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reviewed_at TIMESTAMPTZ NULL,
 reviewed_by INTEGER NULL REFERENCES public.admins(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_supplier_alerts_pending ON public.supplier_alerts (reviewed_at,id DESC);
CREATE INDEX IF NOT EXISTS idx_supplier_alerts_product ON public.supplier_alerts (product_id,id DESC);
ALTER TABLE public.supplier_alerts ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.supplier_alerts FROM PUBLIC,anon,authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.supplier_alerts_id_seq FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.megabot_detect_supplier_alerts()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'public'
AS $function$
BEGIN
 IF TG_OP = 'INSERT' THEN
   IF NEW.supplier_stock IS NOT NULL OR NEW.supplier_unit_price IS NOT NULL THEN
     INSERT INTO public.supplier_alerts
       (product_id,kind,new_supplier_stock,new_supplier_unit_price,source_label)
     VALUES (NEW.id,'nuevo',NEW.supplier_stock,NEW.supplier_unit_price,'Nuevo producto del catálogo importadora');
   END IF;
   RETURN NEW;
 END IF;
 IF OLD.supplier_stock IS NOT DISTINCT FROM NEW.supplier_stock
    AND OLD.supplier_unit_price IS NOT DISTINCT FROM NEW.supplier_unit_price
    AND OLD.supplier_status IS NOT DISTINCT FROM NEW.supplier_status THEN
   RETURN NEW;
 END IF;
 IF (OLD.supplier_status IS DISTINCT FROM 'agotado' AND NEW.supplier_status = 'agotado')
    OR (OLD.supplier_stock > 0 AND NEW.supplier_stock = 0) THEN
   INSERT INTO public.supplier_alerts
      (product_id,kind,old_supplier_stock,new_supplier_stock,
       old_supplier_unit_price,new_supplier_unit_price)
   VALUES (NEW.id,'agotado',OLD.supplier_stock,NEW.supplier_stock,
           OLD.supplier_unit_price,NEW.supplier_unit_price);
 ELSIF (OLD.supplier_status='agotado' AND NEW.supplier_status='disponible')
    OR (OLD.supplier_stock=0 AND NEW.supplier_stock > 0) THEN
   INSERT INTO public.supplier_alerts
      (product_id,kind,old_supplier_stock,new_supplier_stock,
       old_supplier_unit_price,new_supplier_unit_price)
   VALUES (NEW.id,'repuesto',OLD.supplier_stock,NEW.supplier_stock,
           OLD.supplier_unit_price,NEW.supplier_unit_price);
 ELSIF OLD.supplier_stock IS NULL AND NEW.supplier_stock > 0
    AND OLD.supplier_status IS DISTINCT FROM 'agotado' THEN
   INSERT INTO public.supplier_alerts
      (product_id,kind,old_supplier_stock,new_supplier_stock,
       old_supplier_unit_price,new_supplier_unit_price)
   VALUES (NEW.id,'nuevo',OLD.supplier_stock,NEW.supplier_stock,
           OLD.supplier_unit_price,NEW.supplier_unit_price);
 END IF;
 IF OLD.supplier_unit_price IS NOT NULL AND NEW.supplier_unit_price IS NOT NULL
    AND OLD.supplier_unit_price <> NEW.supplier_unit_price THEN
   INSERT INTO public.supplier_alerts
      (product_id,kind,old_supplier_stock,new_supplier_stock,
       old_supplier_unit_price,new_supplier_unit_price)
   VALUES (NEW.id,
           CASE WHEN NEW.supplier_unit_price>OLD.supplier_unit_price THEN 'precio_subio' ELSE 'precio_bajo' END,
           OLD.supplier_stock,NEW.supplier_stock,
           OLD.supplier_unit_price,NEW.supplier_unit_price);
 END IF;
 RETURN NEW;
END
$function$
;
REVOKE ALL ON FUNCTION public.megabot_detect_supplier_alerts() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS megabot_supplier_alerts_trigger ON public.products;
CREATE TRIGGER megabot_supplier_alerts_trigger
AFTER INSERT OR UPDATE OF supplier_stock,supplier_unit_price,supplier_status
ON public.products
FOR EACH ROW EXECUTE FUNCTION public.megabot_detect_supplier_alerts();

-- Solo crea avisos iniciales útiles, nunca recrea los ya existentes.
INSERT INTO public.supplier_alerts (product_id,kind,new_supplier_stock,new_supplier_unit_price,source_label)
SELECT p.id,'nuevo',p.supplier_stock,p.supplier_unit_price,
 'Pendiente inicial de publicación · registro previo de importadora'
FROM public.products p WHERE p.id IN (134,135) AND p.supplier_stock>0
AND NOT EXISTS (SELECT 1 FROM public.supplier_alerts a WHERE a.product_id=p.id AND a.kind='nuevo');

INSERT INTO public.supplier_alerts (product_id,kind,new_supplier_stock,new_supplier_unit_price,source_label)
SELECT p.id,'agotado',p.supplier_stock,p.supplier_unit_price,
 'Pendiente inicial · agotado en el catálogo de importadora'
FROM public.products p WHERE p.supplier_status='agotado'
AND NOT EXISTS (SELECT 1 FROM public.supplier_alerts a WHERE a.product_id=p.id AND a.kind='agotado');
