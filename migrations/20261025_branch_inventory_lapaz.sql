-- Sucursal La Paz: catálogo compartido, unidades separadas y auditoría de traslados.
-- products.stock conserva el inventario de Tienda existente; la nueva sucursal inicia con cero.
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS location VARCHAR(12) NOT NULL DEFAULT 'tienda';
CREATE TABLE IF NOT EXISTS public.branch_stocks (
 product_id INTEGER PRIMARY KEY REFERENCES public.products(id) ON DELETE RESTRICT,
 stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);
CREATE TABLE IF NOT EXISTS public.branch_transfers (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
 admin_id INTEGER NOT NULL REFERENCES public.admins(id) ON DELETE RESTRICT,
 source_location VARCHAR(12) NOT NULL CHECK (source_location IN ('tienda','lapaz')),
 target_location VARCHAR(12) NOT NULL CHECK (target_location IN ('tienda','lapaz')),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_branch_transfers_product ON public.branch_transfers(product_id);
ALTER TABLE public.branch_stocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.branch_transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.branch_stocks,public.branch_transfers FROM anon,authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.branch_transfers_id_seq FROM anon,authenticated;
